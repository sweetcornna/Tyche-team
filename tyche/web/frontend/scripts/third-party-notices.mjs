// Writes dist/THIRD_PARTY_NOTICES.txt: the name, version, license, and license text of every
// production dependency that the built bundle may include. Run after `vite build`.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const npmCli = process.env.npm_execpath ?? (process.platform === "win32" ? join(dirname(process.execPath), "node_modules/npm/bin/npm-cli.js") : undefined);
const paths = execFileSync(npmCli ? process.execPath : "npm", [...(npmCli ? [npmCli] : []), "ls", "--omit=dev", "--all", "--parseable"], { cwd: root, encoding: "utf8" })
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line && resolve(line) !== resolve(root));

const seen = new Map();
for (const dir of paths) {
  const manifest = join(dir, "package.json");
  if (!existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  const licenseFile = readdirSync(dir).find((name) => /^(licen[cs]e|copying|notice)(\.|$)/i.test(name));
  const raw = licenseFile ? readFileSync(join(dir, licenseFile), "utf8") : "";
  const text = raw.replace(/\r\n?/g, "\n").replace(/[ \t]+$/gm, "").trim();
  const license = typeof pkg.license === "string" ? pkg.license : JSON.stringify(pkg.license ?? pkg.licenses ?? "UNKNOWN");
  seen.set(key, { key, license, where: relative(root, dir), text });
}

const entries = [...seen.values()].sort((a, b) => a.key.localeCompare(b.key));
const header =
  "Third-party software bundled in the Tyche web UI (tyche/web/frontend/dist).\n" +
  "Generated by scripts/third-party-notices.mjs from the production dependency tree.\n";
const body = entries
  .map((e) => `${"=".repeat(78)}\n${e.key}  (${e.license})\n${"=".repeat(78)}\n${e.text || "(no license file in the package)"}\n`)
  .join("\n");
writeFileSync(join(root, "dist", "THIRD_PARTY_NOTICES.txt"), `${header}\n${body}`);
console.log(`third-party notices: ${entries.length} packages`);
