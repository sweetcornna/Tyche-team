const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, zh };

export type T = (key: MessageKey, vars?: Record<string, string | number>) => string;

/** `{name}` inserts a variable; `{name|one|other}` picks a word form by whether the number is 1. */
function format(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template;
  return template
    .replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, name, one, other) => (Number(vars[name]) === 1 ? one : other))
    .replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  return format(dictionaries[lang][key] ?? en[key] ?? key, vars);
}

function initialLang(): Lang {
  // An explicit ?lang=zh|en (shared links, screenshots) wins over the saved choice and the browser.
  const param = typeof location !== "undefined" ? new URLSearchParams(location.search).get("lang") : null;
  if (param === "zh" || param === "en") return param;
  try {
    const saved = localStorage.getItem("tyche.lang");
    if (saved === "zh" || saved === "en") return saved;
  } catch {
    /* storage unavailable */
  }
  return typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: T }>({
  lang: "zh",
  setLang: () => undefined,
  t: (key, vars) => translate("zh", key, vars),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("tyche.lang", l);
    } catch {
      /* ignore */
    }
    document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);
  const t = useCallback<T>((key, vars) => translate(lang, key, vars), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
